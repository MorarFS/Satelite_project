export function waybackReleaseToSpec(rel: WaybackRelease): ImageryLayerSpec {
  const year = parseInt(rel.date.slice(0, 4), 10) || 2014;
  return {
    id: `wayback-${rel.releaseNum}`,
    label: `${rel.date} · Esri Wayback (#${rel.releaseNum})`,
    shortLabel: rel.date,
    year,
    dateLabel: rel.date,
    era: year < 2020 ? '2010s' : '2020s',
    kind: 'esri-wayback',
    waybackReleaseNum: rel.releaseNum,
    tileUrl: rel.tileUrl,
    waybackMetadataUrl: rel.metadataUrl,
    sensor: 'Arhivă Sub-metrică prin Esri Wayback',
    resolutionLabel: '0,3 – 0,6 m / px',
    sourceOrg: 'Esri World Imagery Wayback',
    description: `Ediția Esri World Imagery Wayback din ${rel.date} (ID #${rel.releaseNum}).`,
    attribution: `Esri World Imagery Wayback (${rel.date})`,
    maxNativeZoom: 18,
    maxZoom: 19,
    supportsSpectral: false,
  };
}
